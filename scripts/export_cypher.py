"""Regenerates docs/CYPHER_QUERIES.md from a real run, so the documented queries are exactly the ones executed.

Every AegisGraph tool returns a `cypher` trace of the statements it ran. This script seeds throwaway graphs
(prefix `docs_aegis_`), runs the full investigation -> simulation -> remediation -> rollback loop, collects the
traces per tool (deduplicated), and renders them with the tool descriptions. The demo graphs are never touched.

Usage (from the project root):  .venv/Scripts/python.exe scripts/export_cypher.py
"""
from __future__ import annotations

import inspect
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
os.environ["AEGIS_GRAPH_PREFIX"] = "docs_aegis_"
os.environ["AEGIS_KEEP_SANDBOX"] = "false"
sys.path.insert(0, str(ROOT / "backend"))

from aegis import graph as g  # noqa: E402
from aegis import tools  # noqa: E402
from aegis.config import settings  # noqa: E402
from aegis.seed import DEMO_CVE_ID, DEMO_INCIDENT_ID, MEMORY_INDEXES, PROD_INDEXES, incidents, seed_all  # noqa: E402

BRIDGE, ROLE = "legacy-billing-bridge", "LegacyBillingBridgeAdmin"


_CLAUSES = ("OPTIONAL MATCH", "MATCH", "WHERE", "WITH", "RETURN", "ORDER BY", "CALL", "YIELD", "SET", "CREATE",
            "MERGE", "UNWIND", "DELETE", "LIMIT", "ON CREATE SET")


def _clean(cypher: str) -> str:
    """Pretty-print a Cypher statement: one top-level clause per line (never splits inside brackets or strings)."""
    text = " ".join(cypher.split())
    if text.startswith("GRAPH."):
        return text
    out, depth, quote, i = [], 0, "", 0
    while i < len(text):
        ch = text[i]
        if quote:
            out.append(ch)
            if ch == quote:
                quote = ""
            i += 1
            continue
        if ch in "'\"":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if depth == 0 and ch == " ":
            rest = text[i + 1:]
            prev = "".join(out).rstrip()
            hit = next((c for c in _CLAUSES if rest.startswith(c + " ") or rest == c), None)
            if hit and not prev.endswith("OPTIONAL") and not prev.endswith("ON") and not (hit == "SET" and prev.endswith("CREATE")):
                out.append("\n")
                i += 1
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def main() -> None:
    assert settings.graph_prefix == "docs_aegis_"
    seed_all(reset_memory=True)
    alert = incidents(0)[0]["raw_alert"]
    runs: list[tuple[str, dict, dict]] = []

    def call(name: str, **kwargs):
        result = tools.TOOL_REGISTRY[name](**kwargs)
        runs.append((name, kwargs, result))
        return result

    call("recall_similar_incidents", cve_id=DEMO_CVE_ID, package_name="jwt-crypto-core")
    call("find_entry_points", alert_text=alert, top_k=3)
    call("trace_blast_radius", cve_id=DEMO_CVE_ID, max_route_hops=3)
    call("rank_service_criticality")
    call("shortest_attack_path", source_service="auth-token-service", target_database="customer-kyc-vault-db")
    call("expand_neighborhood", service_name="auth-token-service", depth=3)
    call("detect_service_communities")
    call("find_code_owner", cve_id=DEMO_CVE_ID)
    call("simulate_remediation", incident_id=DEMO_INCIDENT_ID, cve_id=DEMO_CVE_ID, bridge_service=BRIDGE, iam_role=ROLE)
    action = call("execute_remediation", incident_id=DEMO_INCIDENT_ID, cve_id=DEMO_CVE_ID, bridge_service=BRIDGE, iam_role=ROLE,
                  justification="documentation run: all exposure paths pivot through the legacy bridge")
    call("get_decision_proof", incident_id=DEMO_INCIDENT_ID)
    call("rollback_remediation", audit_id=action["audit_id"])
    call("read_graph", cypher="MATCH (s:Service)-[:ASSUMES_ROLE]->(r:IAMRole) RETURN s.name, r.name")

    out: list[str] = [
        "# Cypher queries and graph algorithms",
        "",
        "Generated by `scripts/export_cypher.py` from a real run against FalkorDB: every statement below is copied from the",
        "`cypher` trace that each AegisGraph tool returns, so this file is exactly what the product executes. Parameters are shown",
        "as `$name` placeholders with the values used in the run. Regenerate after changing `backend/aegis/tools.py`.",
        "",
        "Graphs: `aegis_prod_graph` (production topology), `aegis_memory_graph` (agent memory), `aegis_sim_<incident>` (sandbox).",
        "Read-only statements run with `GRAPH.RO_QUERY`, so FalkorDB itself rejects writes in them.",
        "",
        "## Contents",
        "",
    ]
    seen_tools: list[str] = []
    for name, _, _ in runs:
        if name not in seen_tools:
            seen_tools.append(name)
    out += [f"- [`{n}`](#{n.replace('_', '-')})" for n in seen_tools] + ["- [Schema and indexes](#schema-and-indexes)", ""]

    for name in seen_tools:
        fn = tools.TOOL_REGISTRY[name]
        out += [f"## {name}", "", inspect.cleandoc(fn.__doc__ or "").replace("\n", " ").replace("  ", " "), ""]
        seen: set[str] = set()
        for tool_name, kwargs, result in runs:
            if tool_name != name:
                continue
            out += [f"Called with `{json.dumps(kwargs)[:300]}`.", ""]
            for trace in result.get("cypher", []):
                text = _clean(trace["cypher"])
                if text in seen:
                    continue
                seen.add(text)
                lang = "text" if text.startswith("GRAPH.") else "cypher"
                graph_kind = "sandbox" if "_sim_" in trace["graph"] else "memory" if trace["graph"].endswith("memory_graph") else "prod"
                params = {k: v for k, v in (trace.get("params") or {}).items()}
                meta = f"graph: `{graph_kind}`, {trace['run_time_ms']} ms server time, {trace['rows']} rows"
                if params:
                    meta += f", params: `{json.dumps(params, default=str)[:400]}`"
                out += [f"```{lang}", text, "```", "", meta, ""]
        out += [""]

    out += [
        "## Schema and indexes",
        "",
        "Created by `backend/aegis/seed.py` (vector dimension = `AEGIS_EMBED_DIM`, default 384):",
        "",
        "```cypher",
        *[s.replace("$dim", str(settings.embed_dim)) for s in PROD_INDEXES],
        "```",
        "",
        "Memory graph:",
        "",
        "```cypher",
        *MEMORY_INDEXES,
        "```",
        "",
    ]
    target = ROOT / "docs" / "CYPHER_QUERIES.md"
    # the run used throwaway graphs; document them under the default graph names
    target.write_text("\n".join(out).replace("docs_aegis_", "aegis_"), encoding="utf-8")
    for name in g.list_graphs():
        if name.startswith("docs_aegis_"):
            g.delete_graph_if_exists(name)
    print(f"wrote {target} ({sum(len(r[2].get('cypher', [])) for r in runs)} traced statements, {len(seen_tools)} tools)")


if __name__ == "__main__":
    main()
